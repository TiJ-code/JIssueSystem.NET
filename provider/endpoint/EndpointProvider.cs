using System.Text.Json;
using System.Text.Json.Nodes;
using JIssueSystem.NET.Api;
using JIssueSystem.NET.Provider.Generic;

namespace JIssueSystem.NET.Provider.endpoint;

/// <summary>
/// Provides issue reporting through a single HTTP endpoint.
/// </summary>
/// <remarks>
/// The configured URL receives a <c>GET</c> request when labels are fetched and
/// a <c>POST</c> request when an issue is reported. Label responses are expected
/// to contain JSON objects with a <c>name</c> property. Optional request headers,
/// label query parameters, and report payload properties allow the provider to
/// adapt to an endpoint's authentication and routing requirements.
/// </remarks>
/// <param name="url">The URL used for both fetching labels and reporting issues.</param>
/// <param name="customPayloadBuilder">
/// An optional builder for report payloads. When omitted, the payload contains
/// <c>title</c>, <c>body</c>, and <c>labels</c> properties.
/// </param>
/// <param name="requestHeaders">Optional headers to send with both requests.</param>
/// <param name="labelQueryParameters">
/// Optional query parameters added to the label-fetching URL. They replace
/// parameters with the same names already present in the URL.
/// </param>
/// <param name="reportPayloadProperties">
/// Optional top-level properties added to every report payload. They replace
/// properties with the same names generated by the payload builder or supplied
/// for an individual report.
/// </param>
/// <example>
/// <code>
/// var provider = new EndpointProvider("https://example.com/issues");
/// var labels = await provider.FetchLabels();
/// var response = await provider.Report(issue);
/// </code>
/// <code>
/// var provider = new EndpointProvider(
///     "https://example.com/issues",
///     requestHeaders: new Dictionary&lt;string, string&gt;
///     {
///         ["X-API-Key"] = "public-key",
///     },
///     labelQueryParameters: new Dictionary&lt;string, string&gt;
///     {
///         ["appId"] = "RulerOfDreams",
///     },
///     reportPayloadProperties: new Dictionary&lt;string, string&gt;
///     {
///         ["appId"] = "RulerOfDreams",
///         ["apiKey"] = "public-key",
///     });
/// </code>
/// </example>
/// <since>0.4.0</since>
public class EndpointProvider(
    string url,
    IPayloadBuilder? customPayloadBuilder = null,
    IReadOnlyDictionary<string, string>? requestHeaders = null,
    IReadOnlyDictionary<string, string>? labelQueryParameters = null,
    IReadOnlyDictionary<string, string>? reportPayloadProperties = null) : IIssueProvider
{
    private static readonly HttpClient Client = new();
    private readonly IReadOnlyDictionary<string, string> _configuredRequestHeaders = requestHeaders is null
        ? new Dictionary<string, string>()
        : new Dictionary<string, string>(requestHeaders);
    private readonly IReadOnlyDictionary<string, string> _configuredLabelQueryParameters = labelQueryParameters is null
        ? new Dictionary<string, string>()
        : new Dictionary<string, string>(labelQueryParameters);
    private readonly IReadOnlyDictionary<string, string> _configuredReportPayloadProperties = reportPayloadProperties is null
        ? new Dictionary<string, string>()
        : new Dictionary<string, string>(reportPayloadProperties);

    /// <summary>
    /// Fetches labels by sending a <c>GET</c> request to the configured URL.
    /// </summary>
    /// <returns>The unique labels parsed from <c>name</c> properties in the response.</returns>
    /// <exception cref="HttpRequestException">
    /// The request failed or the endpoint returned an unsuccessful status code.
    /// </exception>
    public async Task<IReadOnlySet<Label>> FetchLabels()
    {
        using var request = new HttpRequestMessage(HttpMethod.Get, GetLabelsUrl());
        request.Headers.Add("Accept", "application/json");
        AddRequestHeaders(request);

        using var response = await Client.SendAsync(request, HttpCompletionOption.ResponseContentRead);
        response.EnsureSuccessStatusCode();

        var body = await response.Content.ReadAsStringAsync();
        return new GenericLabelParser().ParseLabels(body);
    }

    /// <summary>
    /// Reports an issue by sending a JSON <c>POST</c> request to the configured URL.
    /// </summary>
    /// <param name="issue">The issue to report.</param>
    /// <returns>The response returned by the endpoint.</returns>
    public Task<HttpResponseMessage> Report(Issue issue)
    {
        return Report(issue, null);
    }

    /// <summary>
    /// Reports an issue with additional top-level payload properties.
    /// </summary>
    /// <param name="issue">The issue to report.</param>
    /// <param name="optionalProperties">
    /// Additional string properties to merge into the JSON payload. Existing properties
    /// with the same names are replaced.
    /// </param>
    /// <returns>The response returned by the endpoint.</returns>
    /// <exception cref="JsonException">The generated payload is not valid JSON.</exception>
    /// <exception cref="InvalidOperationException">The generated payload is not a JSON object.</exception>
    public async Task<HttpResponseMessage> Report(Issue issue, Dictionary<string, string>? optionalProperties)
    {
        string payload = customPayloadBuilder?.BuildPayload(issue) ?? JsonSerializer.Serialize(new
        {
            title = issue.Title,
            body = issue.Body,
            labels = issue.Labels.Select(l => l.Name).ToArray(),
        });

        if (optionalProperties is not null && optionalProperties.Count > 0)
        {
            var json = JsonObject.Parse(payload).AsObject();
            foreach (var property in optionalProperties)
            {
                json[property.Key] = property.Value;
            }
            
            payload = JsonSerializer.Serialize(json);
        }

        payload = AddReportPayloadProperties(payload);

        using var request = new HttpRequestMessage(HttpMethod.Post, url)
        {
            Content = new StringContent(payload, System.Text.Encoding.UTF8, "application/json")
        };

        AddRequestHeaders(request);

        return await Client.SendAsync(request);
    }

    private void AddRequestHeaders(HttpRequestMessage request)
    {
        request.Headers.Add("User-Agent", "JIssueSystem");

        foreach (var header in _configuredRequestHeaders)
        {
            request.Headers.Remove(header.Key);
            if (!request.Headers.TryAddWithoutValidation(header.Key, header.Value))
                throw new InvalidOperationException($"'{header.Key}' is not a valid request header.");
        }
    }

    private string GetLabelsUrl()
    {
        if (_configuredLabelQueryParameters.Count == 0)
            return url;

        var uri = new Uri(url, UriKind.Absolute);
        var builder = new UriBuilder(uri);
        var configuredKeys = new HashSet<string>(_configuredLabelQueryParameters.Keys, StringComparer.Ordinal);
        var queryParts = builder.Query
            .TrimStart('?')
            .Split('&', StringSplitOptions.RemoveEmptyEntries)
            .Where(part =>
            {
                var separatorIndex = part.IndexOf('=');
                var key = separatorIndex < 0 ? part : part[..separatorIndex];
                return !configuredKeys.Contains(Uri.UnescapeDataString(key));
            })
            .Concat(_configuredLabelQueryParameters.Select(parameter =>
                $"{Uri.EscapeDataString(parameter.Key)}={Uri.EscapeDataString(parameter.Value)}"));

        builder.Query = string.Join("&", queryParts);
        return builder.Uri.AbsoluteUri;
    }

    private string AddReportPayloadProperties(string payload)
    {
        if (_configuredReportPayloadProperties.Count == 0)
            return payload;

        var json = JsonObject.Parse(payload).AsObject();

        foreach (var property in _configuredReportPayloadProperties)
            json[property.Key] = property.Value;

        return JsonSerializer.Serialize(json);
    }
}
